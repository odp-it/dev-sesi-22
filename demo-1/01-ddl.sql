CREATE TABLE branches (
  branch_id    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  branch_code  VARCHAR2(20)  NOT NULL,
  branch_name  VARCHAR2(100) NOT NULL,
  city         VARCHAR2(50)  NOT NULL,
  CONSTRAINT pk_branches PRIMARY KEY (branch_id),
  CONSTRAINT uq_branches_code UNIQUE (branch_code)
);

CREATE TABLE customers (
  customer_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  cif_no       VARCHAR2(20)  NOT NULL,
  full_name    VARCHAR2(100) NOT NULL,
  email        VARCHAR2(100) NOT NULL,
  phone        VARCHAR2(20),
  segment      VARCHAR2(10)  NOT NULL,
  branch_id    NUMBER        NOT NULL,
  created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT pk_customers PRIMARY KEY (customer_id),
  CONSTRAINT uq_customers_cif UNIQUE (cif_no),
  CONSTRAINT uq_customers_email UNIQUE (email),
  CONSTRAINT fk_customers_branch FOREIGN KEY (branch_id) REFERENCES branches (branch_id)
);

