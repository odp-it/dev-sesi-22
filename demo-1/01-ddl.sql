-- Cek hasil: constraint yang diberi nama (NOT NULL tidak ikut dihitung)
-- P = primary key, U = unique, R = foreign key, C = check
COLUMN table_name FORMAT A14
COLUMN constraint_name FORMAT A26
SELECT table_name, constraint_name, constraint_type
FROM user_constraints
WHERE table_name IN ('BRANCHES', 'CUSTOMERS', 'ACCOUNTS', 'TRANSACTIONS')
  AND constraint_name NOT LIKE 'SYS%'
ORDER BY table_name, constraint_type, constraint_name;
